/**
 * Generates the globe land dots and the flat world map path from Natural Earth data
 * (world-atlas, public domain).
 *
 *   public/media/geo/land-dots.bin  Int16 pairs (lat*100, lon*100) on a Fibonacci sphere
 *   gl/data/worldPath.ts            SVG path (equirectangular, 1000 x 500) for flat maps
 *
 * Run: npm run geo
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { feature } from "topojson-client";
import { geoEquirectangular, geoPath } from "d3-geo";

const root = new URL("..", import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), "utf8"));

// Dots: 50m land for crisp coastlines. Planar ray casting on lon/lat rings with a bbox
// prefilter. Fast and accurate enough at dot scale (world-atlas is cut at the antimeridian).
const landTopo = read("node_modules/world-atlas/land-50m.json");
const land50 = feature(landTopo, landTopo.objects.land);
const polygons = [];
for (const f of land50.features ?? [land50]) {
  const g = f.geometry ?? f;
  const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
  for (const rings of polys) {
    let minX = 180, maxX = -180, minY = 90, maxY = -90;
    for (const [x, y] of rings[0]) {
      if (x < minX) minX = x; if (x > maxX) maxX = x;
      if (y < minY) minY = y; if (y > maxY) maxY = y;
    }
    polygons.push({ rings, minX, maxX, minY, maxY });
  }
}
const inRing = (ring, x, y) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const onLand = (x, y) => {
  for (const p of polygons) {
    if (x < p.minX || x > p.maxX || y < p.minY || y > p.maxY) continue;
    if (!inRing(p.rings[0], x, y)) continue;
    let hole = false;
    for (let r = 1; r < p.rings.length; r++) if (inRing(p.rings[r], x, y)) { hole = true; break; }
    if (!hole) return true;
  }
  return false;
};
const N = 42000;
const golden = Math.PI * (3 - Math.sqrt(5));
const out = [];
for (let i = 0; i < N; i++) {
  const y = 1 - (i / (N - 1)) * 2;
  const theta = golden * i;
  const lat = (Math.asin(y) * 180) / Math.PI;
  const lon = ((((theta * 180) / Math.PI) % 360) + 540) % 360 - 180;
  if (lat < -60) continue; // drop Antarctica, it reads as noise at the bottom of the globe
  if (onLand(lon, lat)) out.push(Math.round(lat * 100), Math.round(lon * 100));
}
mkdirSync(new URL("public/media/geo/", root), { recursive: true });
writeFileSync(new URL("public/media/geo/land-dots.bin", root), Buffer.from(new Int16Array(out).buffer));
console.log(`land dots: ${out.length / 2}`);

// Flat map: 110m is enough at panel size
const land110Topo = read("node_modules/world-atlas/land-110m.json");
const land110 = feature(land110Topo, land110Topo.objects.land);
const projection = geoEquirectangular().scale(1000 / (2 * Math.PI)).translate([500, 250]);
const path = geoPath(projection).digits(1)(land110);
mkdirSync(new URL("gl/data/", root), { recursive: true });
writeFileSync(
  new URL("gl/data/worldPath.ts", root),
  `// Generated by scripts/build-geo.mjs from Natural Earth 110m land. Do not edit.\n// Equirectangular, viewBox 0 0 1000 500.\nexport const WORLD_PATH = ${JSON.stringify(path)};\n`,
);
console.log(`world path: ${(path.length / 1024).toFixed(1)} KB`);
